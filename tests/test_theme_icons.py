"""derby/core/theme/icons.py loads only pre-rendered PNGs (QIcon/QPixmap,
never QtSvg) from assets/brand/, generated by tools/render_assets.py."""
from __future__ import annotations

import pytest

from derby.core.theme import icons
from tools.icon_defs import ICONS


@pytest.mark.parametrize("name", sorted(ICONS.keys()))
@pytest.mark.parametrize("variant", ["dark", "light"])
def test_every_hand_drawn_icon_loads_non_null(qapp, name, variant):
    result = icons.icon(name, variant=variant)
    assert not result.isNull()


def test_icon_rejects_unknown_variant(qapp):
    with pytest.raises(ValueError):
        icons.icon("cashier", variant="blue")


def test_logo_pixmap_variants_load_non_null(qapp):
    for variant in ("transparent", "on-cream", "on-black", "on-amber"):
        pixmap = icons.logo_pixmap(variant, 64)
        assert not pixmap.isNull()
        assert max(pixmap.width(), pixmap.height()) <= 64


def test_icon_mark_pixmap_variants_load_non_null(qapp):
    for variant in ("transparent", "mono-black", "mono-white"):
        pixmap = icons.icon_mark_pixmap(variant, 32)
        assert not pixmap.isNull()
        assert pixmap.height() == 32
