"""Loads the pre-rendered line-icon set and logo marks from assets/brand/
(generated by tools/render_assets.py) via QIcon/QPixmap only -- never
QtSvg at runtime, see CLAUDE.md hard constraint 4.
"""
from __future__ import annotations

from PySide2.QtCore import Qt
from PySide2.QtGui import QIcon, QPixmap

from derby.core.utils.resource_path import resource_path

_ICON_VARIANTS = ("dark", "light")


def icon(name: str, variant: str = "dark", size: int = 24) -> QIcon:
    """`variant` is "dark" (for use on light/cream backgrounds) or "light"
    (cream stroke, for use on the black sidebar/header)."""
    if variant not in _ICON_VARIANTS:
        raise ValueError("variant must be one of {0}, got {1!r}".format(_ICON_VARIANTS, variant))
    result = QIcon()
    for scale_label, scale in (("1x", 1), ("2x", 2)):
        path = resource_path("assets", "brand", "icons", "{0}-{1}-{2}-{3}.png".format(name, variant, size, scale_label))
        if path.exists():
            result.addFile(str(path), mode=QIcon.Normal)
    return result


def logo_pixmap(variant: str, size: int) -> QPixmap:
    """`variant` is one of "transparent", "on-cream", "on-black", "on-amber"."""
    sizes = (256, 512, 1024)
    closest = min(sizes, key=lambda candidate: abs(candidate - size))
    path = resource_path("assets", "brand", "logo-full-{0}-{1}.png".format(variant, closest))
    pixmap = QPixmap(str(path))
    if pixmap.isNull():
        return pixmap
    return pixmap.scaled(size, size, Qt.KeepAspectRatio, Qt.SmoothTransformation)


def login_texture_pixmap() -> QPixmap:
    """A single low-contrast coffee-bean tile for the login screen's
    background only -- see docs/BRAND.md. Callers tile it themselves
    (e.g. via QPainter.drawTiledPixmap)."""
    path = resource_path("assets", "brand", "login-texture-bean-tile.png")
    return QPixmap(str(path))


def icon_mark_pixmap(variant: str, size: int) -> QPixmap:
    """`variant` is one of "transparent", "mono-black", "mono-white"."""
    sizes = (32, 48, 64, 128, 256, 512)
    closest = min(sizes, key=lambda candidate: abs(candidate - size))
    path = resource_path("assets", "brand", "icon-mark-{0}-{1}.png".format(variant, closest))
    pixmap = QPixmap(str(path))
    if pixmap.isNull():
        return pixmap
    return pixmap.scaledToHeight(size, Qt.SmoothTransformation)
